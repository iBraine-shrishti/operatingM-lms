export const STORAGE_KEY_ACTIVE_EXAM = "om_lms_active_exam";
export const STORAGE_KEY_SAVED_EXAMS = "om_lms_saved_exams";

export const getActiveExamConfig = () => {
  try {
    if (typeof window === "undefined") return DEFAULT_EXAM_CONFIG;
    const raw = localStorage.getItem(STORAGE_KEY_ACTIVE_EXAM);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && Array.isArray(parsed.questions) && parsed.questions.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error("Error reading active exam config from localStorage:", e);
  }
  return DEFAULT_EXAM_CONFIG;
};

export const saveActiveExamConfig = (config) => {
  try {
    if (typeof window === "undefined") return false;
    const toSave = {
      ...config,
      updatedAt: new Date().toISOString(),
    };
    localStorage.setItem(STORAGE_KEY_ACTIVE_EXAM, JSON.stringify(toSave));
    return true;
  } catch (e) {
    console.error("Error saving active exam config to localStorage:", e);
    return false;
  }
};

export const resetActiveExamConfig = () => {
  try {
    if (typeof window === "undefined") return false;
    localStorage.removeItem(STORAGE_KEY_ACTIVE_EXAM);
    return true;
  } catch (e) {
    console.error("Error resetting active exam config:", e);
    return false;
  }
};
